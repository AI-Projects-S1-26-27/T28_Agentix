"""Rule engine: evaluates every rule over a window of recent readings.

Regenerate the human-readable rule table with:  python -m reasoning.rule_engine
"""
import json
from pathlib import Path
from typing import Optional

from reasoning.knowledge_base.knowledge_base import THRESHOLDS, Baseline, Reading, Rule, num
from reasoning.models import RuleResult, RuleStatus
from reasoning.rules.fatigue_rules import FATIGUE_RULES
from reasoning.rules.general_rules import GENERAL_RULES
from reasoning.rules.heat_rules import HEAT_RULES
from reasoning.rules.pollution_rules import POLLUTION_RULES

ALL_RULES: tuple[Rule, ...] = HEAT_RULES + POLLUTION_RULES + FATIGUE_RULES + GENERAL_RULES
CONDITIONS_PATH = Path(__file__).parent / "knowledge_base" / "conditions.json"


def missing_inputs(rule: Rule, reading: Reading) -> list[str]:
    """Inputs the rule needs that this reading lacks. A missing value is never
    evidence: that reading is simply skipped for the rule."""
    missing = [f for f in rule.required if num(reading, f) is None]
    for group in rule.required_any:
        if all(num(reading, f) is None for f in group):
            missing.append(" or ".join(group))
    return missing


def evaluate_rule(rule: Rule, readings: list[Reading], baseline: Optional[Baseline]) -> RuleResult:
    window = readings[-rule.window:]
    hits = evaluable = 0
    missing: set[str] = set()
    last_signals: dict = {}
    last_hit_signals: dict = {}

    for reading in window:
        absent = missing_inputs(rule, reading)
        if absent:
            missing.update(absent)
            continue
        evaluable += 1
        hit, signals = rule.check(reading, baseline)
        last_signals = signals
        if hit:
            hits += 1
            last_hit_signals = signals

    result = RuleResult(
        rule_id=rule.rule_id, name=rule.name, category=rule.category,
        status=RuleStatus.NOT_EVALUABLE, weight=rule.weight, hits=hits,
        evaluable=evaluable, window=len(window), min_hits=rule.min_hits,
    )
    if hits >= rule.min_hits:
        result.status = RuleStatus.TRIGGERED
        result.signals = last_hit_signals
        result.explanation = (
            f"{rule.rule_id}: {rule.describe(last_hit_signals)} "
            f"(met in {hits} of the last {len(window)} readings)"
        )
    elif evaluable >= rule.min_hits:
        result.status = RuleStatus.NOT_TRIGGERED
        result.signals = last_signals
    else:
        result.missing_inputs = sorted(missing)
        if missing:
            result.explanation = f"{rule.rule_id} not evaluated: missing {', '.join(sorted(missing))}"
        else:
            result.explanation = (
                f"{rule.rule_id} not evaluated: need {rule.min_hits} readings, have {len(window)}"
            )
    return result


def evaluate_rules(readings: list[Reading], baseline: Optional[Baseline] = None) -> list[RuleResult]:
    return [evaluate_rule(rule, readings, baseline) for rule in ALL_RULES]


def rule_table() -> dict:
    """Rule table + thresholds as plain data (what conditions.json contains)."""
    return {
        "note": "Illustrative prototype values, not clinically validated. Generated by "
                "`python -m reasoning.rule_engine` from the Python rule definitions.",
        "thresholds": THRESHOLDS,
        "rules": [
            {
                "id": r.rule_id,
                "category": r.category.value,
                "name": r.name,
                "description": r.description,
                "requires": list(r.required) + [" or ".join(g) for g in r.required_any],
                "persistence": f"{r.min_hits} of last {r.window} readings",
                "weight": r.weight,
            }
            for r in ALL_RULES
        ],
    }


if __name__ == "__main__":
    CONDITIONS_PATH.write_text(json.dumps(rule_table(), indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {CONDITIONS_PATH}")